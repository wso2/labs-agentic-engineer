package io.ballerina.library.central;

import io.ballerina.library.QualifiedName;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Versions a build has already locked, keyed {@code org/name}.
 *
 * <p>{@code Dependencies.toml} is generated by {@code bal build} and is the most useful answer available: it
 * names the version the component will actually compile against, which is not always the latest.
 *
 * <p>Parsed by hand rather than with the distribution's TOML library because one {@code [[package]]} table
 * shape is the whole requirement, and the alternative couples the tool to a class that is not on the
 * distribution's own runtime classpath.
 *
 * @since 0.1.0
 */
public final class DependenciesToml {

    private static final Pattern ENTRY = Pattern.compile("^(\\w+)\\s*=\\s*\"([^\"]*)\"$");

    private DependenciesToml() {
    }

    public static Map<String, String> parse(String content) {
        Map<String, String> versions = new LinkedHashMap<>();
        Table table = new Table(versions);
        for (String raw : content.split("\n", -1)) {
            String line = raw.trim();
            if (line.startsWith("[[package]]")) {
                table.flush();
                table.inPackage = true;
                continue;
            }
            if (line.startsWith("[")) {
                table.flush();
                table.inPackage = false;
                continue;
            }
            if (!table.inPackage) {
                continue;
            }
            Matcher match = ENTRY.matcher(line);
            if (!match.matches()) {
                continue;
            }
            table.set(match.group(1), match.group(2));
        }
        table.flush();
        return Map.copyOf(versions);
    }

    /**
     * The Ballerina project a directory sits in, found by walking up for a {@code Ballerina.toml}.
     *
     * <p>This is what makes version resolution INTERNAL. The caller used to pass {@code --project-dir}, which
     * meant the tool answered for Central's latest unless an agent knew to name its own project — and T11
     * recorded that the flag was invisible in {@code --help} and spelled differently per verb, so it was never
     * passed. Walking up is what a build does, and it needs no argument.
     *
     * <p>Pure over the path it is given, so a test can drive it against a temporary tree; the process's actual
     * directory is read once, by {@code LibraryTool}, which is the only class allowed to.
     *
     * @return the project root, or {@code null} when the directory is not inside one
     */
    public static Path discoverProject(Path from) {
        if (from == null) {
            return null;
        }
        Path current = from.toAbsolutePath();
        while (current != null) {
            if (Files.isRegularFile(current.resolve("Ballerina.toml"))) {
                return current;
            }
            current = current.getParent();
        }
        return null;
    }

    /**
     * The locked version of one package in a component directory, or {@code null} if a build has not written
     * one. A missing file is not an error — most lookups happen before the first build.
     *
     * <p>The file carries the TRANSITIVE closure rather than the direct imports, which is what makes an internal
     * resolution correct across package boundaries: measured, {@code maintenance_api} imports 8 packages directly
     * and its {@code Dependencies.toml} lists 36, {@code ballerina/auth}, {@code crypto} and {@code jwt} among
     * them. So a cross-package pointer needs no version argument — the project already pins the far side.
     */
    public static String lockedVersion(String projectDir, QualifiedName qualified) {
        String content;
        try {
            content = Files.readString(Path.of(projectDir, "Dependencies.toml"), StandardCharsets.UTF_8);
        } catch (IOException | RuntimeException ignored) {
            return null;
        }
        return parse(content).get(qualified.qualified());
    }

    /** One {@code [[package]]} table being read. A truncated entry is skipped rather than half-read. */
    private static final class Table {

        private final Map<String, String> versions;
        private boolean inPackage;
        private String org;
        private String name;
        private String version;

        private Table(Map<String, String> versions) {
            this.versions = versions;
        }

        private void set(String key, String value) {
            switch (key) {
                case "org" -> org = value;
                case "name" -> name = value;
                case "version" -> version = value;
                default -> {
                    // Every other key of a package table — `repository`, `modules`, `scope` — is metadata
                    // this reader has no use for.
                }
            }
        }

        private void flush() {
            if (inPackage && org != null && name != null && version != null
                    && !org.isEmpty() && !name.isEmpty() && !version.isEmpty()) {
                versions.put(org + "/" + name, version);
            }
            org = null;
            name = null;
            version = null;
        }
    }
}
